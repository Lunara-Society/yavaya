export type StudioText = Record<keyof typeof TEXT, string>;

const CHANGES = ['photo', 'cover', 'background', 'frame', 'decoration', 'look', 'content', 'modules', 'mode', 'privacy'] as const;
export type StudioChangeKind = (typeof CHANGES)[number];

const UNAVAILABLE = ['listings', 'work', 'services', 'store', 'contact'] as const;

function names<T extends string>(t: Translator, prefix: string, ids: readonly T[]): Record<T, string> {
  return Object.fromEntries(ids.map((id) => [id, t(`${prefix}.${id}` as MessageKey)])) as Record<T, string>;
}

export function studioLabels(t: Translator) {
  const styles = [...new Set(IDENTITY_ASSETS.map((asset) => asset.style))];
  return {
    text: Object.fromEntries(Object.entries(TEXT).map(([short, key]) => [short, t(key)])) as StudioText,
    names: {
      accent: names(t, 'studio.accent', STUDIO_ACCENT_IDS),
      surface: names(t, 'studio.surface', STUDIO_SURFACE_IDS),
      solid: names(t, 'studio.solid', STUDIO_SOLID_IDS),
      gradient: names(t, 'studio.gradient', STUDIO_GRADIENT_IDS),
      card: names(t, 'studio.card', STUDIO_CARD_STYLES),
      border: names(t, 'studio.border', STUDIO_BORDERS),
      radius: names(t, 'studio.radius', STUDIO_RADII),
      divider: names(t, 'studio.divider', STUDIO_DIVIDERS),
      typography: names(t, 'studio.type', STUDIO_TYPOGRAPHY),
      header: names(t, 'studio.header', STUDIO_HEADERS),
      density: names(t, 'studio.density', STUDIO_DENSITIES),
      shape: names(t, 'studio.shape', STUDIO_AVATAR_SHAPES),
      mode: names(t, 'studio.mode', PROFILE_MODES),
      module: names(t, 'profile.module', PROFILE_MODULES),
      visibility: names(t, 'studio.visibility', VISIBILITIES),
      visibilityHint: names(t, 'studio.visibility_hint', VISIBILITIES),
      color: names(t, 'studio.color', IDENTITY_COLOR_FAMILIES),
      style: names(t, 'studio.style', styles),
      change: names(t, 'studio.change', CHANGES),
      unavailable: names(t, 'studio.unavailable', UNAVAILABLE),
    },
  };
}

export type StudioLabels = ReturnType<typeof studioLabels>;
